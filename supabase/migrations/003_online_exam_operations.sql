-- RPC: create an exam share.
create or replace function public.create_teacher_exam_share(
  p_quiz_id bigint,
  p_target_school_id text default null,
  p_target_class_name text default null,
  p_start_at timestamptz default null,
  p_end_at timestamptz default null,
  p_duration_minutes integer default 45
) returns table(share_code text)
language plpgsql security definer set search_path=public
as $$
declare c text;
begin
  c := 'FRAH-' || upper(substr(md5(random()::text || clock_timestamp()::text),1,8));
  insert into public.teacher_exam_shares(quiz_id,share_code,target_school_id,target_class_name,start_at,end_at,duration_minutes,active)
  values(p_quiz_id,c,p_target_school_id,p_target_class_name,p_start_at,p_end_at,p_duration_minutes,true);
  return query select c;
end;
$$;

-- RPC: load an active shared exam. Question order/options are randomized on the client.
create or replace function public.get_shared_exam(p_share_code text)
returns jsonb
language plpgsql security definer set search_path=public
as $$
declare s public.teacher_exam_shares; q public.teacher_exams; result jsonb;
begin
  select * into s from public.teacher_exam_shares where share_code=p_share_code and active=true limit 1;
  if not found then return null; end if;
  if s.start_at is not null and now()<s.start_at then return null; end if;
  if s.end_at is not null and now()>s.end_at then return null; end if;
  select * into q from public.teacher_exams where id=s.quiz_id and published=true limit 1;
  if not found then return null; end if;
  result := to_jsonb(q); result := result || jsonb_build_object('share_code',s.share_code,'duration',coalesce(s.duration_minutes,q.duration)); return result;
end;
$$;

create or replace function public.start_shared_teacher_exam(p_share_code text,p_student_id bigint default null,p_student_username text default null)
returns table(attempt_id bigint,duration integer)
language plpgsql security definer set search_path=public
as $$
declare s public.teacher_exam_shares; q public.teacher_exams; a public.teacher_exam_attempts;
begin
  select * into s from public.teacher_exam_shares where share_code=p_share_code and active=true limit 1;
  if not found then raise exception 'آزمون پیدا نشد یا فعال نیست'; end if;
  select * into q from public.teacher_exams where id=s.quiz_id and published=true limit 1;
  if not found then raise exception 'آزمون منتشر نشده است'; end if;
  insert into public.teacher_exam_attempts(quiz_id,student_id,student_username,started_at,status)
  values(q.id,p_student_id,p_student_username,now(),'started') returning * into a;
  return query select a.id,coalesce(s.duration_minutes,q.duration);
end;
$$;

create or replace function public.get_shared_attempt_questions(p_attempt_id bigint)
returns setof public.quiz_questions
language sql security definer set search_path=public
as $$
  select q.* from public.quiz_questions q
  where q.quiz_id=(select quiz_id from public.teacher_exam_attempts where id=p_attempt_id)
  order by random();
$$;

create or replace function public.submit_teacher_exam(p_attempt_id bigint,p_answers jsonb)
returns jsonb
language plpgsql security definer set search_path=public
as $$
declare a public.teacher_exam_attempts; q record; item jsonb; answer text; ok boolean; total numeric:=0; score numeric:=0;
begin
  select * into a from public.teacher_exam_attempts where id=p_attempt_id for update;
  if not found then raise exception 'تلاش آزمون پیدا نشد'; end if;
  for q in select * from public.quiz_questions where quiz_id=a.quiz_id loop
    total := total + coalesce(q.points,1);
    item := coalesce((select x from jsonb_array_elements(p_answers) x where (x->>'question_id')::bigint=q.id limit 1),'{}'::jsonb);
    answer := coalesce(item->>'answer','');
    ok := false;
    if q.question_type <> 'essay' then
      ok := answer=coalesce(q.correct_answer,'') or (q.accepted_answers is not null and answer=any(string_to_array(q.accepted_answers,'|')));
      if ok then score := score + coalesce(q.points,1); end if;
    end if;
    insert into public.teacher_exam_answers(attempt_id,question_id,answer,auto_correct,score) values(a.id,q.id,answer,ok,case when ok then q.points else 0 end);
  end loop;
  update public.teacher_exam_attempts set submitted_at=now(),status='submitted',score=score,max_score=total where id=a.id;
  return jsonb_build_object('score',score,'max_score',total);
end;
$$;

-- Authenticated users may use the operational APIs. Production deployments should
-- tighten these policies with the school's role/profile model.

do $$ declare t text; begin
  foreach t in array array['online_classes','online_class_sessions','online_class_students','online_class_teachers','smart_board_whiteboards','teacher_exams','quiz_questions','teacher_exam_slots','teacher_exam_shares','teacher_exam_attempts','teacher_exam_answers'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('drop policy if exists frahoosh_authenticated_all on public.%I',t);
    execute format('create policy frahoosh_authenticated_all on public.%I for all to authenticated using (true) with check (true)',t);
  end loop;
end $$;

