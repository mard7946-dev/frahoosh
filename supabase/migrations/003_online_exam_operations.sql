-- Frahoosh operational core: online classrooms + online exams.
-- Safe to run after the existing school schema. Every CREATE/ALTER is idempotent.

create table if not exists public.online_classes (
  id bigint generated by default as identity primary key,
  title text not null,
  subject text,
  lesson text,
  teacher text,
  grade text,
  class_name text,
  duration integer not null default 60,
  start_time_shamsi text,
  end_time_shamsi text,
  status text not null default 'inactive',
  join_url text,
  meeting_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.online_class_sessions (
  id bigint generated by default as identity primary key,
  class_id bigint references public.online_classes(id) on delete cascade,
  started_at timestamptz,
  ended_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.online_class_students (
  id bigint generated by default as identity primary key,
  class_id bigint references public.online_classes(id) on delete cascade,
  student_id bigint,
  student_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.online_class_teachers (
  id bigint generated by default as identity primary key,
  class_id bigint references public.online_classes(id) on delete cascade,
  teacher_id bigint,
  teacher_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.smart_board_whiteboards (
  id bigint generated by default as identity primary key,
  class_id bigint,
  content text,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_exams (
  id bigint generated by default as identity primary key,
  teacher_id bigint,
  title text not null,
  subject text,
  grade text,
  class_name text,
  exam_type text default 'آزمون آنلاین',
  duration integer not null default 45,
  description text,
  published boolean not null default false,
  secure_mode boolean not null default true,
  standard_mode boolean not null default true,
  max_attempts integer not null default 1,
  passing_score numeric default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint references public.teacher_exams(id) on delete cascade,
  question text not null,
  option1 text,
  option2 text,
  option3 text,
  option4 text,
  correct_answer text,
  points numeric not null default 1,
  question_type text not null default 'multiple_choice',
  options_json jsonb not null default '[]'::jsonb,
  accepted_answers text,
  difficulty text,
  cognitive_level text,
  auto_grade boolean not null default true,
  negative_score numeric not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_exam_slots (
  id bigint generated by default as identity primary key,
  quiz_id bigint references public.teacher_exams(id) on delete cascade,
  class_name text,
  exam_date_shamsi text,
  start_time_shamsi text,
  end_time_shamsi text,
  duration integer,
  coordinated boolean not null default false,
  secure_mode boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_exam_shares (
  id bigint generated by default as identity primary key,
  quiz_id bigint references public.teacher_exams(id) on delete cascade,
  share_code text unique not null,
  target_school_id text,
  target_class_name text,
  start_at timestamptz,
  end_at timestamptz,
  duration_minutes integer not null default 45,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_exam_attempts (
  id bigint generated by default as identity primary key,
  quiz_id bigint references public.teacher_exams(id) on delete cascade,
  student_id bigint,
  student_username text,
  started_at timestamptz,
  submitted_at timestamptz,
  status text not null default 'started',
  score numeric not null default 0,
  max_score numeric not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_exam_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint references public.teacher_exam_attempts(id) on delete cascade,
  question_id bigint references public.quiz_questions(id) on delete cascade,
  answer text,
  auto_correct boolean,
  score numeric not null default 0,
  teacher_score numeric,
  created_at timestamptz not null default now()
);

create index if not exists idx_online_classes_status on public.online_classes(status);
