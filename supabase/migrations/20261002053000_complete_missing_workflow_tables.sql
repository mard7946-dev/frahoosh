drop policy if exists "meeting_requests_parent_write" on public.meeting_requests;
create policy "meeting_requests_staff_all" on public.meeting_requests for all to authenticated
using ((select private.frahoosh_is_staff())) with check ((select private.frahoosh_is_staff()));
create policy "meeting_requests_owner_read" on public.meeting_requests for select to authenticated
using (
  lower(coalesce(requester_username,'')) = lower(coalesce((select email from auth.users where id=(select auth.uid())),'')) or
  student_id = (select private.frahoosh_current_student_id()) or
  teacher_id = (select private.frahoosh_current_teacher_id())
);
create policy "meeting_requests_parent_write" on public.meeting_requests for all to authenticated
using (
  requester_role in ('parent','parents','ولی','اولیا')
  and lower(coalesce(requester_username,'')) =
      lower(coalesce((select national_code from public.account_settings where auth_user_id=(select auth.uid()) limit 1),''))
)
with check (
  requester_role in ('parent','parents','ولی','اولیا')
  and lower(coalesce(requester_username,'')) =
      lower(coalesce((select national_code from public.account_settings where auth_user_id=(select auth.uid()) limit 1),''))
);

