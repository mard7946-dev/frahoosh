create table if not exists public.meeting_requests (
  id bigint generated by default as identity primary key,
  title text, requester_username text, requester_name text, requester_role text,
  target_username text, target_name text, target_role text,
  student_id integer references public.students(id) on delete set null,
  teacher_id integer references public.teachers(id) on delete set null,
  parent_id text, parent_phone text, requested_day text, requested_date text,
  requested_time text, reason text, description text,
  status text not null default 'pending_manager',
  manager_status text not null default 'pending', educational_status text,
  manager_note text, educational_note text, final_date text, final_time text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.parent_meeting_requests (
  id bigint generated by default as identity primary key,
  parent_id text, parent_name text, parent_username text,
  student_id integer references public.students(id) on delete cascade, student_name text,
  target_role text, target_name text, requested_date_shamsi text, requested_time text,
  reason text, status text not null default 'pending', educational_approval text,
  manager_approval text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.teacher_meetings (
  id bigint generated by default as identity primary key,
  teacher_id bigint references public.teachers(id) on delete set null, teacher_name text,
  student_id bigint references public.students(id) on delete set null, student_name text,
  parent_name text, meeting_at text, subject text, status text not null default 'pending',
  report text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.transport_requests (
  id bigint generated by default as identity primary key,
  parent_username text, student_id bigint references public.students(id) on delete set null,
  address text, vehicle_type text, origin text, destination text, note text,
  status text not null default 'pending', created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_programs (
  id bigint generated by default as identity primary key, activity_key text, title text not null,
  category text, active boolean not null default true, amount integer, settings jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.counseling_classes (
  id bigint generated by default as identity primary key, title text not null, grade text,
  subject text, teacher_id bigint references public.teachers(id) on delete set null,
  active boolean not null default true, created_at timestamptz not null default now()
);

create table if not exists public.counseling_guidance (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  grade text, interest text, aptitude text, recommendation text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.counselor_board (
  id bigint generated by default as identity primary key, title text not null, body text,
  active boolean not null default true, created_by text, created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

