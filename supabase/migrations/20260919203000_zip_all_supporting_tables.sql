do $$
declare t text;
begin
  foreach t in array array[
    'audience_presets','class_seats','discipline_items','discipline_settings',
    'event_audiences','exam_cards','exam_seats','finance_donations','finance_extra',
    'grade_visibility','message_delivery','online_class_activity',
    'online_class_ai_reports','online_class_board_events','online_class_chat',
    'online_class_notifications','online_class_settings','online_presence_checks',
    'online_quizzes','parent_dashboard_events','payment_transactions','permissions',
    'seating','student_dashboard_events','student_files','student_registrations',
    'survey_answers','survey_questions'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists frahoosh_zip_support_authenticated on public.%I', t);
    execute format(
      'create policy frahoosh_zip_support_authenticated on public.%I for all to authenticated using (true) with check (true)',
      t
    );
  end loop;
end $$;
