-- Frahoosh: materialize every remaining supporting table present in the canonical ZIP school.db.
-- These are real backend tables used by the ZIP services/workflows, even when they are
-- not shown as standalone navigation cards. Web and Android can therefore share one
-- complete Supabase data model without decorative/nonexistent tables.

create table if not exists public.audience_presets (
  id bigint generated by default as identity primary key,
  name text,
