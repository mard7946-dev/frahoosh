-- 4) Make the authenticated identity helpers use the same identity sources as login.
create or replace function private.frahoosh_current_role()
returns text language sql stable security definer set search_path=''
as $$
  select coalesce(
    (
      select nullif(trim(coalesce(u.role, a.role, (p.u_permissions->>'role'))),'')
      from public.users u
      full join public.account_settings a
        on lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email',''))
        or lower(coalesce(a.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
      cross join lateral (
        select case when jsonb_typeof(coalesce(u.permissions,'{}'::jsonb))='object'
                    then coalesce(u.permissions,'{}'::jsonb) else '{}'::jsonb end as u_permissions
      ) p
      where lower(coalesce(u.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(u.username,'')) = lower(coalesce(a.username,''))
         or lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or (
           nullif(trim(coalesce(a.national_code,'')),'') is not null
           and lower(trim(coalesce(u.username,''))) = lower(trim(coalesce(a.national_code,'')))
         )
      order by case
        when lower(coalesce(u.username,'')) = lower(coalesce(auth.jwt()->>'email','')) then 0
        when lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email','')) then 1
        else 2
      end
      limit 1
    ),
    ''
  )
$$;

create or replace function private.frahoosh_current_student_id()
returns bigint language sql stable security definer set search_path=''
as $$
  select coalesce(
    (
      select coalesce(u.linked_student_id,a.linked_student_id)
      from public.users u
      full join public.account_settings a
        on lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email',''))
        or lower(coalesce(a.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
      where lower(coalesce(u.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(a.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(u.username,'')) = lower(coalesce(a.national_code,''))
      limit 1
    ),
    (
      select s.id
      from public.students s
      join public.account_settings a on s.national_code=a.national_code
      where lower(coalesce(a.email,''))=lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(a.username,''))=lower(coalesce(auth.jwt()->>'email',''))
      limit 1
    )
  )
$$;

create or replace function private.frahoosh_current_teacher_id()
returns bigint language sql stable security definer set search_path=''
as $$
  select coalesce(
    (
      select coalesce(u.linked_teacher_id,a.linked_teacher_id)
      from public.users u
      full join public.account_settings a
        on lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email',''))
        or lower(coalesce(a.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
      where lower(coalesce(u.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(a.email,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(a.username,'')) = lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(u.username,'')) = lower(coalesce(a.national_code,''))
      limit 1
    ),
    (
      select t.id
      from public.teachers t
      join public.account_settings a on t.national_code=a.national_code
      where lower(coalesce(a.email,''))=lower(coalesce(auth.jwt()->>'email',''))
         or lower(coalesce(a.username,''))=lower(coalesce(auth.jwt()->>'email',''))
      limit 1
    )
  )
$$;

create or replace function private.frahoosh_is_staff()
returns boolean language sql stable security definer set search_path=''
as $$
  select lower(coalesce(private.frahoosh_current_role(),''))
    = any(array[
      'مدیر','مدیریت','manager',
      'معاون آموزشی','educational',
      'معاون اجرایی','اجرایی','executive',
      'معاون پرورشی','cultural',
      'مشاوره','مشاور','counselor','advisor',
      'دبیر','معلم','teacher'
    ])
$$;

-- 5) Ensure the real CRUD tables allow the roles that the Android contract exposes.
-- Manager has full operational access. Educational/executive/cultural/advisor staff
-- can operate the records assigned to their panels; teacher can write teacher-owned data.
do $$
declare t text;
begin
  foreach t in array array[
    'students','teachers','staff','teacher_classes','attendance','grades','student_grades',
    'assignments','discipline_records','educational_followups','academic_followups',
    'teacher_exams','quiz_questions','online_classes','messages','message_targets',
    'message_reads','meeting_requests','school_events','school_class_config',
    'report_cards','weekly_schedule','exam_schedule','finance_accounts',
    'finance_transactions','finance_donations','payment_offers','payment_attempts',
    'payment_records','payment_transactions','certificate_requests','archive_items',
    'assets','student_cards','class_cards','class_seat_assignments','exam_seat_assignments'
  ] loop
    if to_regclass('public.'||t) is not null then
      execute format('drop policy if exists frahoosh_manager_operational_write on public.%I',t);
      execute format(
        'create policy frahoosh_manager_operational_write on public.%I for all to authenticated
         using ((select private.frahoosh_current_role()) = any(array[''manager'',''admin'',''مدیر'',''مدیریت'']))
         with check ((select private.frahoosh_current_role()) = any(array[''manager'',''admin'',''مدیر'',''مدیریت'']))',t);
    end if;
  end loop;
end $$;

