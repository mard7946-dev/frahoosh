-- Frahoosh operational readiness: identity confirmation, robust role resolution,
-- payment fields, and write policies for the real school workflows.
-- Idempotent: preserves existing data and policies.

-- 1) Identity confirmation is server-side and applies to every school member.
create table if not exists public.identity_confirmations (
  id bigint generated by default as identity primary key,
  auth_user_id uuid,
  username text,
  role text not null default 'student',
  profile_table text,
  profile_id bigint,
  student_id bigint,
  confirmation_status text not null default 'confirmed',
  snapshot jsonb default '{}'::jsonb,
  note text,
  confirmed_at timestamptz not null default now()
);
alter table public.identity_confirmations add column if not exists profile_table text;
alter table public.identity_confirmations add column if not exists profile_id bigint;
alter table public.identity_confirmations add column if not exists snapshot jsonb default '{}'::jsonb;
alter table public.identity_confirmations alter column student_id drop not null;

create index if not exists idx_identity_confirmations_user
  on public.identity_confirmations(auth_user_id, confirmed_at desc);
create index if not exists idx_identity_confirmations_username
  on public.identity_confirmations(username, confirmed_at desc);

alter table public.identity_confirmations enable row level security;
drop policy if exists identity_confirmation_insert on public.identity_confirmations;
create policy identity_confirmation_insert on public.identity_confirmations
  for insert to authenticated with check (true);
drop policy if exists identity_confirmation_owner_read on public.identity_confirmations;
create policy identity_confirmation_owner_read on public.identity_confirmations
  for select to authenticated
  using (
    (auth_user_id is not null and auth_user_id = auth.uid())
    or lower(coalesce(username,'')) = lower(coalesce(auth.jwt()->>'email',''))
    or (select private.frahoosh_is_staff())
  );
drop policy if exists identity_confirmation_owner_update on public.identity_confirmations;
create policy identity_confirmation_owner_update on public.identity_confirmations
  for update to authenticated
  using (
    (auth_user_id is not null and auth_user_id = auth.uid())
    or lower(coalesce(username,'')) = lower(coalesce(auth.jwt()->>'email',''))
    or (select private.frahoosh_is_staff())
  )
  with check (
    (auth_user_id is not null and auth_user_id = auth.uid())
    or lower(coalesce(username,'')) = lower(coalesce(auth.jwt()->>'email',''))
    or (select private.frahoosh_is_staff())
  );

