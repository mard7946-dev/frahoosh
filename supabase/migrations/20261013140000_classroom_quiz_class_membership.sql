-- Bind classroom quizzes to the active classroom roster and persist guest/student answers.
create table if not exists public.classroom_quiz_responses (
  id bigint generated by default as identity primary key,
  quiz_id integer not null references public.smart_board_quizzes(id) on delete cascade,
  class_id integer not null references public.online_classes(id) on delete cascade,
  session_id integer not null references public.online_class_sessions(id) on delete cascade,
  student_id integer null references public.students(id) on delete set null,
  guest_user_id uuid null references auth.users(id) on delete cascade,
  student_name text not null,
  student_class text not null default '',
  answer text not null check (answer in ('a','b','c','d')),
  submitted_at timestamptz not null default now(),
  constraint classroom_quiz_responses_one_identity check (
    (student_id is not null and guest_user_id is null) or
    (student_id is null and guest_user_id is not null)
  )
);

create unique index if not exists classroom_quiz_responses_student_once
  on public.classroom_quiz_responses(quiz_id, student_id) where student_id is not null;
create unique index if not exists classroom_quiz_responses_guest_once
  on public.classroom_quiz_responses(quiz_id, guest_user_id) where guest_user_id is not null;
create index if not exists classroom_quiz_responses_class_session
  on public.classroom_quiz_responses(class_id, session_id, submitted_at desc);

alter table public.classroom_quiz_responses enable row level security;
revoke all on public.classroom_quiz_responses from anon;
grant select, insert on public.classroom_quiz_responses to authenticated;
grant usage, select on sequence public.classroom_quiz_responses_id_seq to authenticated;

drop policy if exists classroom_quiz_responses_read_scoped on public.classroom_quiz_responses;
create policy classroom_quiz_responses_read_scoped
on public.classroom_quiz_responses for select to authenticated
using (
  guest_user_id = (select auth.uid())
  or student_id = (select private.frahoosh_current_student_id())
  or exists (
    select 1 from public.online_class_teachers t
    where t.class_id = classroom_quiz_responses.class_id
      and t.teacher_id = (select private.frahoosh_current_teacher_id())
  )
  or lower(coalesce((select private.frahoosh_current_role()),'')) in
    ('manager','مدیر','مدیریت','educational','معاون آموزشی','executive','معاون اجرایی')
);

drop policy if exists classroom_quiz_responses_insert_member on public.classroom_quiz_responses;
create policy classroom_quiz_responses_insert_member
on public.classroom_quiz_responses for insert to authenticated
with check (
  exists (
    select 1 from public.smart_board_quizzes q
    where q.id = classroom_quiz_responses.quiz_id
      and q.class_id = classroom_quiz_responses.class_id
      and q.is_published = true
  )
  and exists (
    select 1 from public.online_class_sessions s
    where s.id = classroom_quiz_responses.session_id
      and s.class_id = classroom_quiz_responses.class_id
      and s.ended_at is null
  )
  and (
    (
      classroom_quiz_responses.student_id is not null
      and classroom_quiz_responses.guest_user_id is null
      and classroom_quiz_responses.student_id = (select private.frahoosh_current_student_id())
      and exists (
        select 1 from public.online_class_students m
        where m.class_id = classroom_quiz_responses.class_id
          and m.student_id = classroom_quiz_responses.student_id
      )
    )
    or
    (
      classroom_quiz_responses.student_id is null
      and classroom_quiz_responses.guest_user_id = (select auth.uid())
      and exists (
        select 1 from public.guest_online_members g
        where g.class_id = classroom_quiz_responses.class_id
          and g.user_id = (select auth.uid())
          and g.role = 'guest'
          and g.left_at is null
      )
    )
  )
);

drop policy if exists smart_board_quizzes_guest_class_read on public.smart_board_quizzes;
create policy smart_board_quizzes_guest_class_read
on public.smart_board_quizzes for select to authenticated
using (
  is_published = true
  and exists (
    select 1 from public.guest_online_members g
    where g.class_id = smart_board_quizzes.class_id
      and g.user_id = (select auth.uid())
      and g.role = 'guest'
      and g.left_at is null
  )
  and exists (
    select 1 from public.online_class_sessions s
    where s.class_id = smart_board_quizzes.class_id
      and s.ended_at is null
  )
);

create or replace function public.register_online_class_student_guest(
  p_class_id integer,
  p_session_id integer,
  p_display_name text,
  p_class_name text
) returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_name text := btrim(coalesce(p_display_name,''));
  v_class text := btrim(coalesce(p_class_name,''));
begin
  if v_uid is null then raise exception 'ورود مهمان معتبر نیست'; end if;
  if v_name = '' or v_class = '' then raise exception 'نام دانش‌آموز و کلاس الزامی است'; end if;
  if not exists (
    select 1 from public.online_class_sessions s
    where s.id = p_session_id and s.class_id = p_class_id and s.ended_at is null
  ) then raise exception 'جلسه کلاس فعال نیست'; end if;
  if not exists (
    select 1 from public.weekly_schedule_entries w
    where w.online_class_id = p_class_id and w.activated_at is not null
      and replace(replace(regexp_replace(lower(btrim(w.class_name)), '\s+', '', 'g'),'ي','ی'),'ك','ک')
        = replace(replace(regexp_replace(lower(v_class), '\s+', '', 'g'),'ي','ی'),'ك','ک')
  ) then raise exception 'این کلاس در برنامه هفتگی به جلسه فعال متصل نیست'; end if;

  update public.guest_online_members
     set display_name = v_name, role = 'guest', left_at = null
   where class_id = p_class_id and user_id = v_uid;
  if not found then
    insert into public.guest_online_members(class_id,user_id,display_name,role)
    values(p_class_id,v_uid,v_name,'guest');
  end if;
  return true;
end;
$$;

revoke all on function public.register_online_class_student_guest(integer,integer,text,text) from public, anon;
grant execute on function public.register_online_class_student_guest(integer,integer,text,text) to authenticated;
